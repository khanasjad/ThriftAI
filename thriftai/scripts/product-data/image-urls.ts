export function getRandomImageForCategory(category: string): string {
  const images = IMAGE_COLLECTIONS[category as keyof typeof IMAGE_COLLECTIONS]
  if (!images || images.length === 0) {
    // Fallback to a default category if category doesn't exist
    const fallbackImages = IMAGE_COLLECTIONS.CLOTHING
    return fallbackImages[Math.floor(Math.random() * fallbackImages.length)]
  }
  return images[Math.floor(Math.random() * images.length)]
}

export function getMultipleImagesForCategory(category: string, count: number = 3): string[] {
  const images = IMAGE_COLLECTIONS[category as keyof typeof IMAGE_COLLECTIONS]
  if (!images || images.length === 0) {
    const fallbackImages = IMAGE_COLLECTIONS.CLOTHING
    return fallbackImages.slice(0, count)
  }

  const result: string[] = []
  const availableImages = [...images]

  for (let i = 0; i < count && availableImages.length > 0; i++) {
    const randomIndex = Math.floor(Math.random() * availableImages.length)
    result.push(availableImages.splice(randomIndex, 1)[0])
  }

  return result
}